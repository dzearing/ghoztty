//! `ghoztty-setup.exe` - the installer's front door (T2197;
//! `src/apprt/win32/setup_main.zig`). Windows targets only.
//!
//! It embeds the MSI named by `-Dsetup-msi` (release-windows.yml publishes it
//! as `Ghoztty-Setup-<version>-x64.exe`, T2198). Without the option it is built
//! with no package, which is what every dev build and the acceptance script
//! get: the Debug seams hand it a package or a result instead. Like the
//! custom-action DLL it is NOT part of the installed product and no delivery
//! manifest lists it; it is installed into `zig-out/bin` so the acceptance
//! script and the release job find it where they find everything else.
//!
//! It shares the app's dialog (`ConfirmDialog`) but not the app: the root
//! declares itself app-less (`dialog_app.zig`), so the binary is the dialog,
//! Win32 and msi.dll's API - no terminal, no renderer, no config.

const Setup = @This();

const std = @import("std");
const Config = @import("Config.zig");
const setMsvcGuiEntry = @import("win32_entry.zig").setMsvcGuiEntry;

install_step: *std.Build.Step.InstallArtifact,

pub fn init(b: *std.Build, cfg: *const Config) Setup {
    // The payload module: one generated file whose only declaration is the
    // embedded package (or an empty slice). A generated module rather than a
    // build option, because @embedFile only reaches files in its own module.
    const wf = b.addWriteFiles();
    const payload_src = if (cfg.setup_msi) |msi| blk: {
        _ = wf.addCopyFile(.{ .cwd_relative = msi }, "payload.msi");
        break :blk wf.add("payload.zig",
            \\//! Generated by src/build/GhosttySetup.zig: the package this setup installs.
            \\pub const msi: []const u8 = @embedFile("payload.msi");
            \\
        );
    } else wf.add("payload.zig",
        \\//! Generated by src/build/GhosttySetup.zig: built without -Dsetup-msi.
        \\pub const msi: []const u8 = "";
        \\
    );

    const module = b.createModule(.{
        .root_source_file = b.path("src/setup_main.zig"),
        .target = cfg.target,
        .optimize = cfg.optimize,
        .strip = cfg.strip,
    });
    module.addImport("setup_payload", b.createModule(.{ .root_source_file = payload_src }));

    const exe = b.addExecutable(.{
        .name = "ghoztty-setup",
        .root_module = module,
        .use_llvm = true,
    });
    // Debug keeps the console so std.log reaches the acceptance script, the
    // same rule as ghoztty.exe; every other build is a GUI exe that opens no
    // console behind the dialog.
    exe.subsystem = if (cfg.optimize == .Debug) .Console else .Windows;
    if (exe.subsystem == .Windows) setMsvcGuiEntry(exe);
    exe.linkSystemLibrary("user32");
    exe.linkSystemLibrary("gdi32");
    exe.linkSystemLibrary("comctl32");
    exe.linkSystemLibrary("uxtheme");
    exe.linkSystemLibrary("dwmapi");
    exe.linkSystemLibrary("shell32");
    exe.linkSystemLibrary("advapi32");
    const file_ver = cfg.windows_file_version;
    exe.addWin32ResourceFile(.{
        .file = b.path("dist/windows/ghoztty-setup.rc"),
        .flags = &.{
            "/d", b.fmt("GHOZTTY_FILE_VER={d},{d},{d},{d}", .{
                file_ver[0], file_ver[1], file_ver[2], file_ver[3],
            }),
            "/d", b.fmt("GHOZTTY_FILE_VER_STR=\"{d}.{d}.{d}.{d}\"", .{
                file_ver[0], file_ver[1], file_ver[2], file_ver[3],
            }),
        },
    });
    return .{ .install_step = b.addInstallArtifact(exe, .{}) };
}

pub fn install(self: *const Setup) void {
    const b = self.install_step.step.owner;
    b.getInstallStep().dependOn(&self.install_step.step);
}
